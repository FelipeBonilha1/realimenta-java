-- ReAlimenta SP — estrutura Oracle
-- Executar manualmente uma vez, em um schema vazio, com o arquivo em UTF-8.
-- A aplicacao Spring nao executa este script.
-- Este script nao apaga objetos. Se precisar recomecar, use 03_limpeza_manual.sql de proposito.

ALTER SESSION SET TIME_ZONE = 'America/Sao_Paulo';

-- Comecam em 5 para nao colidir com os identificadores 1 a 4 da demonstracao.
CREATE SEQUENCE SEQ_ESTABELECIMENTO START WITH 5 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_INSTITUICAO START WITH 5 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_LOTE_ALIMENTO START WITH 5 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_DOACAO START WITH 5 INCREMENT BY 1 NOCACHE NOCYCLE;

CREATE TABLE ESTABELECIMENTO (
    ID       NUMBER(19)         NOT NULL,
    NOME     VARCHAR2(120 CHAR) NOT NULL,
    TIPO     VARCHAR2(30 CHAR)  NOT NULL,
    EMAIL    VARCHAR2(150 CHAR) NOT NULL,
    TELEFONE VARCHAR2(20 CHAR)  NOT NULL,
    ENDERECO VARCHAR2(200 CHAR) NOT NULL,
    BAIRRO   VARCHAR2(80 CHAR)  NOT NULL,
    CIDADE   VARCHAR2(80 CHAR)  NOT NULL,
    CONSTRAINT PK_ESTABELECIMENTO PRIMARY KEY (ID),
    CONSTRAINT UK_ESTABELECIMENTO_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_ESTABELECIMENTO_TIPO CHECK (
        TIPO IN ('RESTAURANTE', 'PADARIA', 'SUPERMERCADO', 'HOTEL', 'COZINHA_INDUSTRIAL', 'OUTRO')
    )
);

CREATE TABLE INSTITUICAO (
    ID       NUMBER(19)         NOT NULL,
    NOME     VARCHAR2(120 CHAR) NOT NULL,
    EMAIL    VARCHAR2(150 CHAR) NOT NULL,
    TELEFONE VARCHAR2(20 CHAR)  NOT NULL,
    ENDERECO VARCHAR2(200 CHAR) NOT NULL,
    BAIRRO   VARCHAR2(80 CHAR)  NOT NULL,
    CIDADE   VARCHAR2(80 CHAR)  NOT NULL,
    CONSTRAINT PK_INSTITUICAO PRIMARY KEY (ID),
    CONSTRAINT UK_INSTITUICAO_EMAIL UNIQUE (EMAIL)
);

CREATE TABLE LOTE_ALIMENTO (
    ID                    NUMBER(19)         NOT NULL,
    ESTABELECIMENTO_ID    NUMBER(19)         NOT NULL,
    DESCRICAO             VARCHAR2(255 CHAR) NOT NULL,
    CATEGORIA             VARCHAR2(30 CHAR)  NOT NULL,
    QUANTIDADE_KG         NUMBER(10,3)       NOT NULL,
    PRAZO_APROVEITAMENTO  TIMESTAMP(6)       NOT NULL,
    STATUS                VARCHAR2(20 CHAR)  NOT NULL,
    CONSTRAINT PK_LOTE_ALIMENTO PRIMARY KEY (ID),
    CONSTRAINT FK_LOTE_ESTABELECIMENTO FOREIGN KEY (ESTABELECIMENTO_ID) REFERENCES ESTABELECIMENTO (ID),
    CONSTRAINT CK_LOTE_QUANTIDADE CHECK (QUANTIDADE_KG > 0),
    CONSTRAINT CK_LOTE_CATEGORIA CHECK (
        CATEGORIA IN ('PREPARADO', 'IN_NATURA', 'PANIFICADOS', 'LATICINIOS', 'MERCEARIA', 'OUTROS')
    ),
    CONSTRAINT CK_LOTE_STATUS CHECK (
        STATUS IN ('DISPONIVEL', 'RESERVADO', 'COLETADO', 'ENTREGUE', 'CANCELADO')
    )
);

CREATE TABLE DOACAO (
    ID                      NUMBER(19)    NOT NULL,
    LOTE_ID                 NUMBER(19)    NOT NULL,
    INSTITUICAO_ID          NUMBER(19)    NOT NULL,
    STATUS                  VARCHAR2(20 CHAR) NOT NULL,
    DATA_RESERVA            TIMESTAMP(6)  NOT NULL,
    DATA_COLETA             TIMESTAMP(6),
    DATA_ENTREGA            TIMESTAMP(6),
    QUANTIDADE_ENTREGUE_KG  NUMBER(10,3),
    CONSTRAINT PK_DOACAO PRIMARY KEY (ID),
    CONSTRAINT UK_DOACAO_LOTE UNIQUE (LOTE_ID),
    CONSTRAINT FK_DOACAO_LOTE FOREIGN KEY (LOTE_ID) REFERENCES LOTE_ALIMENTO (ID),
    CONSTRAINT FK_DOACAO_INSTITUICAO FOREIGN KEY (INSTITUICAO_ID) REFERENCES INSTITUICAO (ID),
    CONSTRAINT CK_DOACAO_STATUS CHECK (
        STATUS IN ('RESERVADA', 'COLETADA', 'ENTREGUE', 'CANCELADA')
    ),
    CONSTRAINT CK_DOACAO_QUANTIDADE CHECK (
        QUANTIDADE_ENTREGUE_KG IS NULL OR QUANTIDADE_ENTREGUE_KG > 0
    ),
    CONSTRAINT CK_DOACAO_COERENCIA CHECK (
        (STATUS = 'RESERVADA' AND DATA_COLETA IS NULL AND DATA_ENTREGA IS NULL AND QUANTIDADE_ENTREGUE_KG IS NULL)
        OR (STATUS = 'COLETADA' AND DATA_COLETA IS NOT NULL AND DATA_ENTREGA IS NULL AND QUANTIDADE_ENTREGUE_KG IS NULL)
        OR (STATUS = 'ENTREGUE' AND DATA_COLETA IS NOT NULL AND DATA_ENTREGA IS NOT NULL AND QUANTIDADE_ENTREGUE_KG IS NOT NULL)
        OR (STATUS = 'CANCELADA' AND DATA_COLETA IS NULL AND DATA_ENTREGA IS NULL AND QUANTIDADE_ENTREGUE_KG IS NULL)
    )
);

-- Listagem de lotes realmente disponiveis: STATUS e prazo ainda nao ultrapassado.
CREATE INDEX IDX_LOTE_STATUS_PRAZO ON LOTE_ALIMENTO (STATUS, PRAZO_APROVEITAMENTO);

-- Consulta de historico antes de excluir o estabelecimento e apoio da chave estrangeira.
CREATE INDEX IDX_LOTE_ESTABELECIMENTO ON LOTE_ALIMENTO (ESTABELECIMENTO_ID);

-- Historico da instituicao, chave estrangeira e indicador de instituicoes com entrega.
CREATE INDEX IDX_DOACAO_INSTITUICAO ON DOACAO (INSTITUICAO_ID);

COMMENT ON TABLE ESTABELECIMENTO IS 'Estabelecimento que oferta alimento excedente.';
COMMENT ON TABLE INSTITUICAO IS 'Instituicao social que pode reservar um lote inteiro.';
COMMENT ON TABLE LOTE_ALIMENTO IS 'Oferta integral. Nao ha divisao do mesmo lote entre instituicoes.';
COMMENT ON TABLE DOACAO IS 'No maximo uma doacao por lote. Cancelamento nao apaga a linha.';
COMMENT ON COLUMN LOTE_ALIMENTO.PRAZO_APROVEITAMENTO IS 'Hora civil de America/Sao_Paulo, com 6 digitos fracionarios. Nao e laudo sanitario. Nao ha migracao: TIMESTAMP sem precisao ja e TIMESTAMP(6).';
COMMENT ON COLUMN LOTE_ALIMENTO.QUANTIDADE_KG IS 'Quilos registrados na oferta. Nao significa quilos entregues.';
COMMENT ON COLUMN DOACAO.QUANTIDADE_ENTREGUE_KG IS 'Preenchido somente na confirmacao da entrega.';

COMMIT;
